package com.bassstrings.database.domain;

import com.bassstrings.database.api.model.Role;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;

import java.time.Instant;
import java.util.LinkedHashSet;
import java.util.Set;

/**
 * A subscriber account. Created (or matched) on first successful OAuth2 login by
 * {@link com.bassstrings.hub.security.AccountProvisioningOAuth2UserService}.
 *
 * Note: this reuses the {@link Role} enum generated by openapi-generator from the
 * OpenAPI contract rather than defining a duplicate persistence-layer enum. Roles are
 * a small, stable value set shared identically between the API and the domain, so the
 * duplication cost of a second enum plus a mapper isn't worth paying here; every other
 * domain concept below has its own persistence type, independent of the generated DTOs.
 */
@Document(collection = "users")
public class UserAccount {

    @Id
    private String id;

    /** "google", "facebook", or "apple". */
    private String provider;

    /** The subject/user id assigned by the provider (OAuth2 "sub" claim). */
    private String providerId;

    @Indexed(unique = true)
    private String email;

    private String displayName;

    private String avatarUrl;

    private Set<Role> roles = new LinkedHashSet<>(Set.of(Role.USER));

    @CreatedDate
    private Instant createdAt;

    @LastModifiedDate
    private Instant updatedAt;

    public UserAccount() {
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getProvider() {
        return provider;
    }

    public void setProvider(String provider) {
        this.provider = provider;
    }

    public String getProviderId() {
        return providerId;
    }

    public void setProviderId(String providerId) {
        this.providerId = providerId;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getDisplayName() {
        return displayName;
    }

    public void setDisplayName(String displayName) {
        this.displayName = displayName;
    }

    public String getAvatarUrl() {
        return avatarUrl;
    }

    public void setAvatarUrl(String avatarUrl) {
        this.avatarUrl = avatarUrl;
    }

    public Set<Role> getRoles() {
        return roles;
    }

    public void setRoles(Set<Role> roles) {
        this.roles = roles;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }
}
